package no.nav.arbeidsgiver.tiltakrefusjon.refusjon

enum class Tiltakstype {
    MIDLERTIDIG_LONNSTILSKUDD, VARIG_LONNSTILSKUDD, SOMMERJOBB, VTAO, MENTOR, FIREARIG_LONNSTILSKUDD, INKLUDERINGSTILSKUDD;

    fun utbetalesAutomatisk() = when (this) {
        MIDLERTIDIG_LONNSTILSKUDD, VARIG_LONNSTILSKUDD, SOMMERJOBB, FIREARIG_LONNSTILSKUDD, INKLUDERINGSTILSKUDD -> false
        VTAO, MENTOR -> true
    }

    fun harFastUtbetalingssum() = when (this) {
        MIDLERTIDIG_LONNSTILSKUDD, VARIG_LONNSTILSKUDD, FIREARIG_LONNSTILSKUDD, SOMMERJOBB, INKLUDERINGSTILSKUDD -> false
        VTAO, MENTOR -> true
    }

    fun har5gBegrensning() = when (this) {
        VARIG_LONNSTILSKUDD, FIREARIG_LONNSTILSKUDD -> true
        MIDLERTIDIG_LONNSTILSKUDD, SOMMERJOBB, VTAO, MENTOR, INKLUDERINGSTILSKUDD -> false
    }
}
